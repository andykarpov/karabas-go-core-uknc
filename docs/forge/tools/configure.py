#!/usr/bin/env python3
"""One source of truth for OSD indices and hardware switches."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
items=[]; bindings=[]
def heading(name): items.append(dict(type='H',name=name))
def switch(name, signal, options, default=0):
    bindings.append((len(items),signal,default,len(options)))
    items.append(dict(type='S',name=name,options=options,default=default))
def file(name,slot,ext): items.append(dict(type='FL' if slot==5 else 'F',name=name,slot=slot,extensions="."+ext,dir='/mc0511-media',autoload=0))
heading('MC-0511 UKNC')
file('FDD0',0,'dsk');file('Run SAV',5,'sav');file('HDD0',4,'img')
for name,signal,hotkey in [('Reset','reset_sw','F12'),('Cold boot','cold_sw','Menu+F12')]:
    bindings.append((len(items),signal,0,2));items.append(dict(type='T',name=name,default=0,hotkey=hotkey))
heading('Hardware')
switch('Volume','system_volume',['Mute','33%','66%','100%'],1)
switch('Beeper','system_beeper',['Off','On'],1)
switch('Covox','system_covox',['Off','177372','177100 LPT','Both'])
switch('Kakave mouse','system_mouse_en',['Off','On'])
heading('Aberrant')
for n in range(3):switch(f'AY{n+1}',f'system_ay_en[{n}]',['Off','On'],1)
switch('Stereo','system_stereo',['Mono','ABC'],1)
switch('Low-pass','system_lowpass',['Off','On'],1)
switch('Old freaks','system_oldfreaks',['Off','On'])
heading('Floppy drives')
switch('FDD controller','system_fdd_en',['Off','On'],1)
for n in range(4):
    if n:file(f'FDD{n}',n,'dsk')
    switch(f'FDD{n} write prot',f'system_floppy_wprot[{n}]',['Off','On'])
switch('Physical FDD','system_physical_fdd',['None','A','B','C','D'])
heading('Hard disk')
switch('HDD controller','system_hdd_en',['Off','On'])
switch('HDD write prot','system_hdd_wprot',['Off','On'])
switch('Image format','system_hdd_mode',['Auto','Plain','Inversed'])
switch('HDD delay us','system_hdd_delay',[str(i*25) for i in range(40)],30)
heading('RTC clock')
switch('RTC controller','system_rtc_en',['Off','On'])
for name,field,options,default in [('Year',0,[str(y) for y in range(2020,2040)],6),('Month',1,[str(x) for x in range(1,13)],0),('Day',2,[str(x) for x in range(1,32)],0),('Hour',3,[str(x) for x in range(24)],0),('Minute',4,[str(x) for x in range(60)],0)]:switch(name,f'rtc:{field}',options,default)
heading('Video')
switch('Color','system_video',['RGB','BGR'])
heading('About')
items += [dict(type='P',name=s) for s in ['UKNC FPGA: Alex Gurov','Tang v2: Sergei Lemeshev','UKNCBTL: nzeemin','BadApple: blairecas','Peripherals: xrust; tests: reddie']]
core=dict(id='mc0511',name='UKNC MC-0511',build='26103102',bitstream='karabas_go.bin',visible=True,type='osd',order=5,eeprom_bank=255,rtc_mode=1,roms=[],osd=items,spi_freq=16,buttons={'btn1':'core','btn2':{'press':'osd','hold':'menu','hold_ms':3000}})
(ROOT/'config/core.json').write_text(json.dumps(core,indent=2)+'\n')
(ROOT/'config/switches.json').write_text(json.dumps(bindings,indent=2)+'\n')
# This include lives in the same module as the retained Tang device instances.
signals={'system_video':1,'reset_sw':1,'cold_sw':1,'system_volume':2,'system_floppy_wprot':4,'system_hdd_mode':2,'system_hdd_wprot':1,'system_hdd_delay':6,'system_beeper':1,'system_ay_en':3,'system_covox':2,'system_stereo':1,'system_lowpass':1,'system_oldfreaks':1,'system_fdd_en':1,'system_hdd_en':1,'system_mouse_en':1,'system_rtc_en':1}
defaults={s:0 for s in signals}
signals['system_physical_fdd']=3
defaults['system_physical_fdd']=0
for _,s,d,_ in bindings:
    if s.startswith('rtc:'):continue
    if '[' in s:defaults[s.split('[')[0]]|=d<<int(s[-2])
    else:defaults[s]=d
out='// Generated by configure.py. Do not renumber OSD items independently.\n'
for s,width in signals.items():out+=f'reg [{width-1}:0] {s} = {width}\'d{defaults[s]};\n'
out+='''wire [1:0] system_reset = {cold_sw, reset_sw | cold_sw | host_buttons[0]};
wire system_mouse = 1'b1;
reg [7:0] system_hdd_spt=0, system_hdd_heads=0, system_hdd_flags=0;
reg [15:0] system_hdd_cyl=0;
reg system_rtc_tgl=0;
reg [2:0] system_rtc_field=0;
reg [7:0] system_rtc_val=0;
reg [15:0] previous_switch=16'hffff;
always @(posedge clk_25) begin
 if (softsw_command != previous_switch) begin
  previous_switch <= softsw_command;
  case(softsw_command[15:8])
'''
for i,s,d,n in bindings:
    val='softsw_command[7:0]'
    if s.startswith('rtc:'):line=f'begin system_rtc_field <= 3\'d{s[4:]}; system_rtc_val <= {val}; system_rtc_tgl <= ~system_rtc_tgl; end'
    elif s=='system_physical_fdd':line=f'{s} <= ({val} <= 4) ? softsw_command[2:0] : 3\'d0;'
    else:line=f'{s} <= {val};'
    out+=f"   8'd{i}: {line}\n"
for i,s in [(240,'system_hdd_spt'),(241,'system_hdd_heads'),(242,'system_hdd_flags'),(243,'system_hdd_cyl[7:0]'),(244,'system_hdd_cyl[15:8]')]:out+=f"   8'd{i}: {s} <= softsw_command[7:0];\n"
out+="   8'd245: begin system_rtc_field<=3'd5;system_rtc_val<=softsw_command[7:0];system_rtc_tgl<=~system_rtc_tgl;end\n"
out+='  endcase\n end\nend\n'
(ROOT/'src/rtl/switches.inc').write_text(out)
print(f'{len(items)} Karabas menu entries')
